package com.msi.inspector.domain.analyzer

object AppPermissionGuidance {
    fun explain(permission: String): String {
        val value = permission.lowercase()
        return when {
            value.contains("camera") -> "قد تحتاجه ميزات التصوير أو مسح QR أو مكالمات الفيديو. راجع ما إذا كانت هذه الوظيفة موجودة فعلًا في التطبيق."
            value.contains("record_audio") -> "قد تحتاجه المكالمات أو التسجيل أو الأوامر الصوتية. راجع متى يطلب التطبيق الميكروفون."
            value.contains("location") -> "قد تحتاجه الخرائط أو الطقس أو الخدمات المرتبطة بالموقع. تحقق من الحاجة إلى الموقع أثناء الاستخدام أو في الخلفية."
            value.contains("contacts") -> "قد يستخدم لمزامنة جهات الاتصال أو اقتراح الأصدقاء. تأكد أن الميزة تبرر الوصول إلى دفتر العناوين."
            value.contains("sms") -> "قد يرتبط بقراءة الرسائل أو إرسالها أو التحقق من رموز الدخول. هذه صلاحية حساسة تستحق مراجعة دقيقة."
            value.contains("call_log") || value.contains("phone_state") || value.contains("call_phone") -> "قد يرتبط بوظائف الاتصال أو معلومات حالة الهاتف. راجع ما إذا كانت وظيفة التطبيق تتطلب ذلك."
            value.contains("calendar") -> "قد يستخدم لإضافة المواعيد أو مزامنة التقويم. راجع هل يقدّم التطبيق وظيفة تقويم فعلية."
            value.contains("bluetooth") || value.contains("nearby") -> "قد يستخدم للاتصال بأجهزة قريبة أو ملحقات. تحقق من توافق ذلك مع وظيفة التطبيق."
            value.contains("post_notifications") -> "تسمح بإظهار الإشعارات. راجع أهمية التنبيهات التي يرسلها التطبيق."
            value.contains("read_media") || value.contains("external_storage") || value.contains("media") -> "قد يستخدم لاختيار صور أو ملفات أو حفظها. فضّل محدد الملفات/الصور إذا كان متاحًا بدل الوصول الأوسع."
            value.contains("body_sensors") || value.contains("activity_recognition") -> "قد يستخدم لقياس النشاط أو بيانات اللياقة. تحقق من أن هذه ميزة أساسية في التطبيق."
            else -> "لا يمكن استنتاج الغرض من اسم الإذن وحده. راجع وصف التطبيق ووثائق المطوّر، ولا تمنح الإذن إلا عند الحاجة."
        }
    }

    fun explainSpecialAccess(signal: String): String = when {
        signal.contains("إمكانية الوصول") ->
            "إمكانية الوصول قد تسمح بقراءة عناصر الشاشة أو تنفيذ إجراءات نيابة عن المستخدم. اتركها مفعّلة فقط عندما تحتاجها ميزة واضحة مثل قارئ شاشة."
        signal.contains("مسؤول جهاز") ->
            "مسؤول الجهاز قد يملك صلاحيات إدارية مثل قفل الجهاز أو فرض سياسات. لا تفعّله إلا إذا كنت تعرف الوظيفة التي تتطلبه."
        signal.contains("الظهور فوق التطبيقات") ->
            "قد يستخدم لإظهار فقاعات أو عناصر عائمة. راجع هل يتطلب التطبيق عرض واجهة فوق تطبيقات أخرى."
        signal.contains("إحصاءات الاستخدام") ->
            "يمكن أن يكشف أنماط استخدام التطبيقات. امنحه فقط لتطبيق موثوق ولغرض مفهوم."
        else ->
            "راجع سبب طلب هذا الإعداد من داخل التطبيق ووثائق المطوّر، وتحقق من أنه ضروري للميزة التي تستخدمها."
    }
}
